const Gen = (() => {
  const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
  const rnd = (min, max) => Math.floor(min + Math.random() * (max - min + 1));

  // Пытаемся не повторять прошлое значение при перегенерации
  function pickNew(arr, prev) {
    let v = pick(arr);
    for (let i = 0; i < 6 && v === prev && arr.length > 1; i++) v = pick(arr);
    return v;
  }

  function name(typeId, prev) {
    let v = pick(CUTE_WORDS) + '-' + pick(CREATURES[typeId]);
    for (let i = 0; i < 6 && v === prev; i++) v = pick(CUTE_WORDS) + '-' + pick(CREATURES[typeId]);
    return v;
  }

  function power(typeId, prev) {
    // 60% подходящая типу, 40% общая
    const pool = Math.random() < 0.6 ? POWERS_TYPE[typeId] : POWERS_COMMON;
    return pickNew(pool, prev);
  }

  function rarity() {
    const total = RARITIES.reduce((s, r) => s + r.weight, 0);
    let roll = Math.random() * total;
    for (const r of RARITIES) {
      roll -= r.weight;
      if (roll < 0) return r.id;
    }
    return RARITIES[0].id;
  }

  function stats(rarityId) {
    const r = RARITIES.find((x) => x.id === rarityId);
    const count = rnd(3, 4);
    const names = STAT_NAMES.slice().sort(() => Math.random() - 0.5).slice(0, count);
    return names.map((k) => ({ k, v: rnd(r.min, r.max) }));
  }

  function roll(typeId) {
    const rar = rarity();
    return { type: typeId, name: name(typeId), power: power(typeId), rarity: rar, stats: stats(rar) };
  }

  return { name, power, rarity, stats, roll, pick };
})();
